def glossary_json(doc, lang):
    entries = []
    forms = RU_FORMS if lang == "ru" else EN_FORMS if lang == "en" else {}
    for book in doc["books"]:
        if book["kind"] != "glossary":
            continue
        for section in book["sections"]:
            for kind, payload in section["blocks"]:
                if kind != "dt":
                    continue
                title, definition = map(plain, payload)
                aliases = {title}
                for part in re.split(r"\s*/\s*", title):
                    aliases.add(re.sub(r"\s*\([^)]*\)", "", part).strip())
                    aliases.update(re.findall(r"\(([^)]+)\)", part))
                for alias in tuple(aliases):
                    aliases.update(filter(None, forms.get(alias, "").split("|")))
                entries.append({"title": title, "definition": definition,
                                "forms": sorted(filter(None, aliases))})
    if lang == "ru":
        title = "Стоячая волна"
        entries.append({
            "title": title,
            "definition": (
                "Возникает при наложении одинаковых волн, идущих навстречу друг другу. "
                "Узор остаётся на месте: в одних точках колебания гасят друг друга, "
                "в других — усиливают. Так дрожит натянутая струна. "
                "В §2 это образ порядка: неподвижность узора держится на движении, "
                "а не на его отсутствии."
            ),
            "forms": [title, *RU_FORMS[title].split("|")],
        })
    elif lang == "en":
        title = "Standing wave"
        entries.append({
            "title": title,
            "definition": (
                "Forms when identical waves traveling in opposite directions overlap. "
                "The pattern stays in place: at some points the oscillations cancel, "
                "at others they reinforce one another. A taut string vibrates this way. "
                "In §2 this is an image of order: the pattern's stillness depends on "
                "movement, not on its absence."
            ),
            "forms": [title, *EN_FORMS[title].split("|")],
        })
    # Data, never executable markup. Also safe for a literal </script> in
    # a future glossary definition.
    return json.dumps(entries, ensure_ascii=False).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
