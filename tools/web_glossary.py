from html.parser import HTMLParser


class PlainText(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []

    def handle_data(self, data):
        self.parts.append(data)


def plain(fragment):
    parser = PlainText()
    parser.feed(fragment)
    return "".join(parser.parts)


